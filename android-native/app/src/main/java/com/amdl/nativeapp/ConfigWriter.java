package com.amdl.nativeapp;

import android.content.Context;
import android.util.Log;

import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.Charset;
import java.util.Map;

/**
 * Writes the {@code config.yaml} the bundled CLI reads.
 *
 * <p>The option set mirrors the upstream config.yaml (and the Termux menu script
 * am.sh), except for everything that needs a terminal or ffmpeg: those stay at
 * values that cannot fail on a phone.
 */
public final class ConfigWriter {

    private ConfigWriter() {
    }

    /**
     * 生成 config.yaml：优先用上游模板（能自动带上 App 不认识的新配置项），
     * 模板缺失或不可用时退回手写版本，保证下载不会因为一个 asset 问题就失败。
     */
    public static File write(Context context, File configFile, Prefs prefs) throws IOException {
        ConfigTemplate template = ConfigTemplate.load(context);
        if (template != null) {
            Map<String, String> known = ConfigKeys.values(prefs);
            Map<String, String> forced = ConfigKeys.forced();
            known.putAll(forced);
            // ffmpeg 被伪装成 libffmpeg.so 打包，安装后解到 nativeLibraryDir；
            // 那是 Android 上唯一允许执行自定义文件的目录。
            String ffmpeg = ffmpegPath(context);
            if (ffmpeg != null) {
                known.put(ConfigKeys.KEY_FFMPEG_PATH, ffmpeg);
            }
            Map<String, String> overrides = ConfigTemplate.overridesFrom(prefs);
            overrides.putAll(forced);
            String yaml;
            try {
                yaml = template.render(known, overrides);
            } catch (Throwable e) {
                yaml = null;
            }
            if (yaml != null && sanityCheck(yaml)) {
                // 模板来自上游，不一定含 general.ui-language：缺了就补一行
                ConfigTemplate.write(configFile, ensureUiLanguage(yaml, prefs.uiLanguage()));
                return configFile;
            }
            Log.w("ConfigWriter", "template output rejected, using built-in writer");
        }
        return writeLegacy(context, configFile, prefs);
    }

    /**
     * 转码入口的绝对路径。
     *
     * <p>优先返回兼容层 libffmpegshim.so：它把上游用的 ffmpeg 4.3+ 参数改写成 3.3.2 能懂的
     * 形式，并在转完后把封面写回文件。兼容层缺失时退回真正的 ffmpeg。
     */
    static String ffmpegPath(Context context) {
        try {
            String dir = context.getApplicationInfo().nativeLibraryDir;
            File shim = new File(dir, "libffmpegshim.so");
            if (shim.isFile()) {
                return shim.getAbsolutePath();
            }
            File real = new File(dir, "libffmpeg.so");
            return real.isFile() ? real.getAbsolutePath() : null;
        } catch (Throwable e) {
            return null;
        }
    }

    /** 真正的 ffmpeg（检测等场景直接用它，不走参数改写）。 */
    static String realFFmpegPath(Context context) {
        try {
            File real = new File(context.getApplicationInfo().nativeLibraryDir, "libffmpeg.so");
            return real.isFile() ? real.getAbsolutePath() : null;
        } catch (Throwable e) {
            return null;
        }
    }

    /**
     * 保证 {@code general.ui-language} 存在：上游模板可能还没加这一项，
     * 而 App 与核心都靠它决定语言。已存在就原样返回。
     */
    static String ensureUiLanguage(String yaml, String tag) {
        if (yaml == null) {
            return null;
        }
        if (yaml.contains("ui-language:")) {
            return yaml;
        }
        String line = "  ui-language: \"" + (tag == null ? "zh" : tag) + "\"\n";
        int general = yaml.indexOf("general:");
        if (general < 0) {
            return "general:\n" + line + yaml;
        }
        int eol = yaml.indexOf('\n', general);
        if (eol < 0) {
            return yaml + "\n" + line;
        }
        return yaml.substring(0, eol + 1) + line + yaml.substring(eol + 1);
    }

    /** 路径是下载能不能落地的关键，模板万一丢了这几项就退回手写版本。 */
    private static boolean sanityCheck(String yaml) {
        return yaml.contains("lite-server:")
                && yaml.contains("alac:")
                && yaml.contains("atmos:")
                && yaml.contains("aac:")
                && yaml.contains("mv:");
    }

    private static File writeLegacy(Context context, File configFile, Prefs prefs) throws IOException {
        StringBuilder y = new StringBuilder(4096);

        // 配置文件自身是技术产物，注释统一用英文，避免随界面语言变化
        y.append("# Generated by the Android app; change settings in the app, not here.\n");
        y.append("general:\n");
        y.append("  lite-server: ").append(quote(prefs.liteServer())).append('\n');
        y.append("  ui-language: ").append(quote(prefs.uiLanguage())).append('\n');
        y.append("  media-user-token: ").append(quote(prefs.mediaUserToken())).append('\n');
        y.append("  language: ").append(quote(prefs.language())).append('\n');
        y.append("  max-memory-limit: ").append(prefs.maxMemory()).append('\n');
        y.append("  proxy: ").append(quote(prefs.proxy())).append('\n');
        y.append("  storefront: ").append(quote(prefs.storefront())).append('\n');
        y.append("  authorization-token: ").append(quote(prefs.authorizationToken())).append('\n');
        // 手机上没有终端：失败立即退出，而不是等待「按回车重试」
        y.append("  exit-on-error: true\n");

        y.append("media:\n");
        y.append("  get-m3u8-mode: ").append(quote(prefs.m3u8Mode())).append('\n');
        y.append("  alac-max: ").append(prefs.alacMax()).append('\n');
        y.append("  atmos-max: ").append(prefs.atmosMax()).append('\n');
        y.append("  aac-type: ").append(quote(prefs.aacType())).append('\n');
        y.append("  alac-fix: ").append(prefs.alacFix()).append('\n');
        y.append("  mv:\n");
        y.append("    audio-type: ").append(quote(prefs.mvAudioType())).append('\n');
        y.append("    max: ").append(prefs.mvMax()).append('\n');

        y.append("paths:\n");
        y.append("  alac: ").append(quote(prefs.dirAlac())).append('\n');
        y.append("  atmos: ").append(quote(prefs.dirAtmos())).append('\n');
        y.append("  aac: ").append(quote(prefs.dirAac())).append('\n');
        y.append("  mv: ").append(quote(prefs.dirMv())).append('\n');
        y.append("  album-folder: ").append(quote(prefs.albumTemplate())).append('\n');
        y.append("  playlist-folder: ").append(quote(prefs.playlistTemplate())).append('\n');
        y.append("  artist-folder: ")
                .append(quote(prefs.artistFolder() ? prefs.artistTemplate() : "")).append('\n');
        y.append("  song-file: ").append(quote(prefs.songTemplate())).append('\n');
        y.append("  limit-max: ").append(prefs.limitMax()).append('\n');
        y.append("  explicit: ").append(quote(prefs.tagExplicit())).append('\n');
        y.append("  clean: ").append(quote(prefs.tagClean())).append('\n');
        y.append("  apple-master: ").append(quote(prefs.tagMaster())).append('\n');

        y.append("metadata:\n");
        y.append("  lyrics:\n");
        y.append("    save-file: ").append(prefs.lyricsSave()).append('\n');
        y.append("    embed: ").append(prefs.lyricsEmbed()).append('\n');
        y.append("    type: ").append(quote(prefs.lyricsType())).append('\n');
        y.append("    format: ").append(quote(prefs.lyricsFormat())).append('\n');
        y.append("    extra: ").append(quote(prefs.lyricsExtra())).append('\n');
        y.append("  artwork:\n");
        y.append("    embed: ").append(prefs.coverEmbed()).append('\n');
        y.append("    size: ").append(quote(prefs.coverSize())).append('\n');
        y.append("    format: ").append(quote(prefs.coverFormat())).append('\n');
        y.append("    save-artist: ").append(prefs.coverSaveArtist()).append('\n');
        // 动态封面需要 ffmpeg，App 不内置
        y.append("    save-animated: false\n");
        y.append("    emby-animated: false\n");
        y.append("    dl-for-playlist: false\n");
        y.append("  tags:\n");
        y.append("    sort-order: ").append(prefs.tagSortOrder()).append('\n');
        y.append("    itunes-id: ").append(prefs.tagItunesId()).append('\n');
        y.append("    use-songinfo-for-playlist: ").append(prefs.tagUseSonginfo()).append('\n');

        // 内置 ffmpeg（libffmpeg.so）：转码默认关闭，由用户在配置里开启
        y.append("convert:\n");
        y.append("  after-download: ").append(prefs.convertEnabled()).append('\n');
        y.append("  format: ").append(quote(prefs.convertFormat())).append('\n');
        y.append("  keep-original: ").append(prefs.convertKeepOriginal()).append('\n');
        y.append("  skip-if-source-matches: true\n");
        String ffmpeg = ffmpegPath(context);
        y.append("  ffmpeg-path: ").append(quote(ffmpeg == null ? "ffmpeg" : ffmpeg)).append('\n');
        y.append("  extra-args: \"\"\n");
        y.append("  with-metadata: true\n");
        y.append("  warn-lossy-to-lossless: false\n");
        y.append("  skip-lossy-to-lossless: true\n");
        y.append("  check-bad-alac: false\n");
        y.append("  delete-bad-alac: false\n");

        File parent = configFile.getParentFile();
        if (parent != null && !parent.exists() && !parent.mkdirs()) {
            throw new IOException(Strings.get("err.dir.create", parent));
        }
        try (OutputStream out = new FileOutputStream(configFile)) {
            out.write(y.toString().getBytes(Charset.forName("UTF-8")));
        }
        return configFile;
    }

    private static String quote(String value) {
        String v = value == null ? "" : value;
        StringBuilder sb = new StringBuilder(v.length() + 8);
        sb.append('"');
        for (int i = 0; i < v.length(); i++) {
            char c = v.charAt(i);
            if (c == '"' || c == '\\') {
                sb.append('\\');
            }
            sb.append(c);
        }
        sb.append('"');
        return sb.toString();
    }
}
